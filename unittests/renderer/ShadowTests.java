package renderer;

import static java.awt.Color.BLUE;

import org.junit.jupiter.api.Test;

import geometries.*;
import lighting.*;
import primitives.*;
import scene.Scene;

/**
 * Testing basic shadows in a 3D rendering environment.
 * These tests verify the correct implementation of shadow casting from light sources.
 * @author Dan Zilberstein
 */
class ShadowTests {
   /** Default constructor to satisfy JavaDoc generator. */
   ShadowTests() { /* to satisfy JavaDoc generator */ }

   /** Scene of the tests. */
   private final Scene          scene      = new Scene("Test scene");
   /** Camera builder for the tests. Configured for a specific viewpoint and image size. */
   private final Camera.Builder camera     = Camera.getBuilder()
           .setLocation(new Point(0, 0, 1000))
           .setDirection(Point.ZERO, Vector.AXIS_Y)
           .setVpDistance(1000)
           .setVpSize(200, 200)
           .setRayTracer(scene, RayTracerType.SIMPLE);

   /** The sphere geometry used in the tests. It emits blue light and has specific material properties. */
   private final Intersectable  sphere     = new Sphere(60d, new Point(0, 0, -200))
           .setEmission(new Color(BLUE))
           .setMaterial(new Material().setKD(0.5).setKS(0.5).setShininess(30));
   /** The material properties applied to the triangles in the tests. */
   private final Material       trMaterial = new Material().setKD(0.5).setKS(0.5).setShininess(30);

   /**
    * Helper function for the shadow tests involving a sphere and a triangle.
    * This method sets up the scene with the predefined sphere and a given triangle,
    * adds a spotlight at a specified location, and then renders and saves the image.
    *
    * @param pictName     The name of the picture file to be generated by the test.
    * @param triangle     The {@link Triangle} object to be added to the scene. Its emission color is set to blue
    * and its material is set to {@link #trMaterial}.
    * @param spotLocation The {@link Point} representing the location of the {@link SpotLight} in the scene.
    */
   private void sphereTriangleHelper(String pictName, Triangle triangle, Point spotLocation) {
      scene.geometries.add(sphere, triangle.setEmission(new Color(BLUE)).setMaterial(trMaterial));
      scene.light //
              .add(new SpotLight(new Color(400, 240, 0), spotLocation, new Vector(1, 1, -3)) //
                      .setKl(1E-5).setKq(1.5E-7));
      camera
              .setResolution(400, 400) //
              .build() //
              .renderImage() //
              .writeToImage(pictName);
   }

   /**
    * Produces a picture of a sphere and a triangle, illuminated by a point light,
    * demonstrating a specific shadow configuration by moving the triangle.
    * The triangle is placed slightly behind the sphere relative to the light source.
    */
   @Test
   void sphereTriangleMove1() {
      sphereTriangleHelper("shadowSphereTriangleMove2", //
              new Triangle(new Point(-60, -30, 0), new Point(-30, -60, 0), new Point(-58, -58, -4)), //
              new Point(-100, -100, 200));
   }

   /**
    * Produces a picture of a sphere and a triangle, illuminated by a point light,
    * demonstrating another shadow configuration by moving the triangle.
    * The triangle is placed differently behind the sphere to show a varied shadow.
    */
   @Test
   void sphereTriangleMove2() {
      sphereTriangleHelper("shadowSphereTriangleMove1", //
              new Triangle(new Point(-50, -20, 0), new Point(-20, -50, 0), new Point(-48, -48, -4)), //
              new Point(-100, -100, 200));
   }

   /**
    * Produces a picture of a sphere and a triangle, illuminated by a spot light,
    * demonstrating a specific shadow configuration with the spotlight in a particular position.
    * The triangle's position creates a shadow from the sphere.
    */
   @Test
   void sphereTriangleSpot1() {
      sphereTriangleHelper("shadowSphereTriangleSpot1", //
              new Triangle(new Point(-70, -40, 0), new Point(-40, -70, 0), new Point(-68, -68, -4)), //
              new Point(-90, -90, 150));
   }

   /**
    * Produces a picture of a sphere and a triangle, illuminated by a spot light,
    * demonstrating another shadow configuration with the spotlight moved closer.
    * This test shows the effect of changing the spotlight's position on the shadow.
    */
   @Test
   void sphereTriangleSpot2() {
      sphereTriangleHelper("shadowSphereTriangleSpot2", //
              new Triangle(new Point(-70, -40, 0), new Point(-40, -70, 0), new Point(-68, -68, -4)), //
              new Point(-80, -80, 100));
   }


   /**
    * Produces a picture of two triangles lighted by a spot light with a Sphere
    * producing a shading effect. This test demonstrates how a sphere can cast shadows
    * onto other geometries in the scene.
    */
   @Test
   void trianglesSphere() {
      scene.geometries //
              .add( //
                      new Triangle(new Point(-150, -150, -115), new Point(150, -150, -135), new Point(75, 75, -150)) //
                              .setMaterial(new Material().setKS(0.8).setShininess(60)), //
                      new Triangle(new Point(-150, -150, -115), new Point(-70, 70, -140), new Point(75, 75, -150)) //
                              .setMaterial(new Material().setKS(0.8).setShininess(60)), //
                      new Sphere(30d, new Point(0, 0, -11)) //
                              .setEmission(new Color(BLUE)) //
                              .setMaterial(new Material().setKD(0.5).setKS(0.5).setShininess(30)) //
              );
      scene.setAmbientLight(new AmbientLight(new Color(38, 38, 38)));
      scene.light //
              .add(new SpotLight(new Color(700, 400, 400), new Point(40, 40, 115), new Vector(-1, -1, -4)) //
                      .setKl(4E-4).setKq(2E-5));

      camera//
              .setResolution(600, 600) //
              .build() //
              .renderImage() //
              .writeToImage("shadowTrianglesSphere");
   }

}